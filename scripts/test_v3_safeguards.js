const assert = require('node:assert/strict');
const puppeteer = require('puppeteer-core');
const path = require('node:path');

(async () => {
  const browser = await puppeteer.launch({
    executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage']
  });
  try {
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.setViewport({ width: 1080, height: 1920, deviceScaleFactor: 1 });
    await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }]);
    await page.goto('file://' + path.resolve(__dirname, '../lucky_drop/v3/index.html'));
    const snap = () => page.evaluate(() => window.__techDropQA.snapshot());
    assert.equal((await snap()).reducedMotion, true, 'canvas must respect reduced motion');
    assert.equal(await page.$eval('#operatorModal', el => el.inert), true, 'closed settings must not accept keyboard focus');
    assert.equal(await page.$eval('#result', el => el.inert), true, 'hidden results must not accept keyboard focus');
    assert.equal(await page.evaluate(() => {
      document.getElementById('stage').focus();
      document.getElementById('resultMute').focus();
      document.getElementById('cfgEventTitle').focus();
      return document.activeElement.id;
    }), 'stage', 'inert content must reject programmatic focus');
    assert.equal(await page.$eval('#scene', c => c.width), 1080, 'backing pixels must follow display enlargement');
    await page.keyboard.down('Shift'); await page.keyboard.press('KeyO'); await page.keyboard.up('Shift');
    await page.focus('#saveConfig');
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'closeConfig', 'modal Tab must wrap');
    await page.keyboard.down('Shift'); await page.keyboard.press('Tab'); await page.keyboard.up('Shift');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'saveConfig', 'modal Shift+Tab must wrap');
    await page.focus('#cfgEventTitle');
    await page.keyboard.press('Space');
    assert.equal((await snap()).state, 'idle', 'typing in settings must never start the game');
    await page.$eval('#cfgEffects', el => { el.value = '25'; });
    await page.$eval('#cfgAutoReset', el => { el.checked = false; });
    await page.click('#saveConfig');
    await page.reload();
    await page.evaluate(() => window.__techDropQA.openConfig());
    assert.equal(await page.$eval('#cfgEffects', el => el.value), '25', 'operator settings must survive reload');
    await page.evaluate(() => window.__techDropQA.closeConfig());
    await page.click('#start');
    await page.waitForFunction(() => document.documentElement.dataset.state === 'playing');
    assert.equal((await snap()).ballColor, '#D8FF3E', 'drop must not disclose the result colour');
    await page.evaluate(() => window.__techDropQA.skip());
    await page.evaluate(() => window.__techDropQA.skip());
    assert.ok((await snap()).activeVoices <= 12, 'audio voices must be bounded');
    await page.focus('#resultMute');
    await page.keyboard.press('Space');
    assert.equal((await snap()).state, 'result', 'keyboard activation of sound must not reset the result');
    await page.waitForFunction(() => window.__techDropQA.snapshot().masterLevel === 0, { timeout: 1000 });
    const muted = await snap();
    assert.equal(muted.muted, true);
    assert.equal(muted.masterLevel, 0, 'mute must silence existing and scheduled sounds');
    assert.equal(await page.$eval('#playAgain', el => el.hidden), false, 'manual mode needs a touch-accessible next round');
    await page.click('#playAgain');
    assert.equal((await snap()).state, 'launch');
    await page.evaluate(() => window.__techDropQA.reset());
    assert.equal((await snap()).activeVoices, 0, 'reset must stop scheduled voices');
    assert.equal((await snap()).pendingPulses, 0, 'reset must cancel delayed peg pulses');
    await page.evaluate(() => window.__techDropQA.setQuality('low'));
    assert.equal(await page.$eval('#scene', c => c.width), 540, 'low preset must reduce backing resolution');
    await page.evaluate(() => window.__techDropQA.setQuality('high'));
    assert.equal(await page.$eval('#scene', c => c.width), 1080);
    await page.keyboard.down('Shift'); await page.keyboard.press('KeyD'); await page.keyboard.up('Shift');
    await page.focus('#skip');
    await page.keyboard.press('Space');
    assert.equal((await snap()).state, 'launch', 'native debug skip must start once');
    await page.focus('#skip');
    await page.keyboard.press('Enter');
    assert.equal((await snap()).state, 'capture', 'native debug skip must advance once');
    await page.focus('#skip');
    await page.keyboard.press('Space');
    assert.equal((await snap()).state, 'result');
    await page.focus('#forceReset');
    await page.keyboard.press('Enter');
    assert.equal((await snap()).state, 'idle', 'native debug reset must reset without starting again');
    await page.evaluate(() => window.__techDropQA.openConfig());
    await page.focus('#cfgEventTitle');
    await page.evaluate(() => window.__techDropQA.reset());
    assert.equal(await page.evaluate(() => document.activeElement.id), 'cfgEventTitle', 'round reset must preserve settings focus');
    await page.keyboard.press('Space');
    assert.equal((await snap()).state, 'idle', 'reset while editing must not enable a background keyboard launch');
    await page.$eval('#cfgAutoReset', el => { el.checked = true; });
    await page.click('#saveConfig');
    await page.evaluate(() => { window.__techDropQA.start(); window.__techDropQA.skip(); window.__techDropQA.skip(); });
    await page.evaluate(() => window.__techDropQA.openConfig());
    await page.$eval('#cfgAutoReset', el => { el.checked = false; });
    await page.click('#saveConfig');
    assert.equal(await page.$eval('#playAgain', el => el.hidden), false, 'disabling auto-reset on a live result must expose replay');
    assert.equal(await page.$eval('.result-bar', el => el.hidden), true);
    await page.evaluate(() => window.__techDropQA.openConfig());
    await page.$eval('#cfgAutoReset', el => { el.checked = true; });
    await page.click('#saveConfig');
    assert.equal(await page.$eval('#playAgain', el => el.hidden), true);
    assert.equal(await page.$eval('.result-bar', el => el.hidden), false);
    await page.evaluate(() => window.__techDropQA.reset());
    await page.evaluate(() => window.__techDropQA.openConfig());
    await page.$eval('#cfgFpsToggle', el => { el.checked = true; });
    await page.click('#saveConfig');
    assert.equal(await page.$eval('#perfHud', el => el.style.display), 'block', 'saving the operator HUD checkbox must show the HUD');
    await page.evaluate(() => window.__techDropQA.openConfig());
    await page.$eval('#cfgFpsToggle', el => { el.checked = false; });
    await page.click('#saveConfig');
    assert.equal(await page.$eval('#perfHud', el => el.style.display), 'none');
    assert.deepEqual(errors, []);
    console.log('Safeguards: reduced motion, sharp scaling, settings/input, neutral drop, audio mute/budget/reset, quality resizing PASS');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
